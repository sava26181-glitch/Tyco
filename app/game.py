def clamp(v, lo=0, hi=100):
    return max(lo, min(hi, v))


def rating(st: dict) -> int:
    w = {"stamina": .15, "charm": .2, "smart": .25, "rep": .2, "net": .2}
    score = sum(st.get(k, 0) * w[k] for k in w)
    if st.get("health", 100) < 40:
        score -= (40 - st["health"]) * .3
    return int(clamp(round(score)))


def tier(score: int) -> str:
    return [name for low, name in TIERS if score >= low][-1]


def grow(value: int, amount: int) -> int:
    if amount <= 0:
        return clamp(value + amount)
    slow = 1 if value < 50 else .7 if value < 70 else .45 if value < 85 else .25
    return clamp(value + max(1, round(amount * slow)))


