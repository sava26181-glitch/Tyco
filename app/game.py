def roll(table, rnd):
    total = sum(x[1] for x in table)
    r = rnd.uniform(0, total)
    for row in table:
        r -= row[1]
        if r <= 0:
            return row[0]
    return table[-1][0]


def chance(table, name):
    return next(round(w * 100 / sum(x[1] for x in table), 1) for n, w in table if n == name)


